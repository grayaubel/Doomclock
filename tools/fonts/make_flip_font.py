"""Generate src/gateway/flip_font.h: anti-aliased 8-bit alpha bitmaps of the digits for the flip clock.

    python3 tools/fonts/make_flip_font.py [--font path/to/Roboto[wdth,wght].ttf] [--weight 400]

Two sizes:
  BIG   digits 0-9 and '-', digit height 125 px (the flip cards on the home screen)
  SMALL digits 0-9, ':' and '-', digit height 18 px (the wake-time pill)
Default font: Roboto (Apache-2.0), variable weight. Any .ttf/.otf works.
"""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_FONT = os.path.expanduser("~/Library/Fonts/Roboto[wdth,wght].ttf")


def load(path, size, weight):
    f = ImageFont.truetype(path, size)
    try:
        axes = f.get_variation_axes()
        vals = []
        for a in axes:
            name = a.get("name", b"")
            name = name.decode() if isinstance(name, bytes) else name
            if name.lower().startswith("weight"):
                vals.append(weight)
            else:
                vals.append(a.get("default", a["minimum"]))
        f.set_variation_by_axes(vals)
    except (OSError, AttributeError):
        pass                                    # not a variable font
    return f


def size_for_height(path, weight, target):
    size = target
    for _ in range(30):
        f = load(path, size, weight)
        l, t, r, b = f.getbbox("0", anchor="ls")
        h = b - t
        if abs(h - target) <= 0:
            break
        size = max(4, round(size * target / h))
    return load(path, size, weight), size


def render(font, chars):
    asc = max(-font.getbbox(c, anchor="ls")[1] for c in "0123456789")    # top of the tallest digit
    desc = max(font.getbbox(c, anchor="ls")[3] for c in "0123456789")    # overshoot below baseline
    cap_h = asc + desc
    glyphs, data = [], []
    for c in chars:
        adv = round(font.getlength(c))
        pad = 8
        W, H = adv + 2 * pad, cap_h + 2 * pad
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((pad, pad + asc), c, font=font, fill=255, anchor="ls")
        bb = img.getbbox()
        if bb is None:
            glyphs.append((len(data), 0, 0, 0, 0, adv)); continue
        x0, y0, x1, y1 = bb
        crop = img.crop(bb)
        glyphs.append((len(data), x1 - x0, y1 - y0, x0 - pad, y0 - pad, adv))
        data.extend(crop.tobytes())
    return cap_h, glyphs, data


def emit(name, chars, cap_h, glyphs, data):
    out = [f"// {name}: chars \"{chars}\", cap height {cap_h} px, {len(data)} bytes",
           f"#define {name}_CAP_H {cap_h}",
           f"static const FlipGlyph {name}_GLYPHS[{len(glyphs)}] = {{"]
    for c, g in zip(chars, glyphs):
        out.append("  {%d, %d, %d, %d, %d, %d},   // '%s'" % (*g, c))
    out.append("};")
    out.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    out.append("};\n")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--weight", type=int, default=400)
    ap.add_argument("--big", type=int, default=125)
    ap.add_argument("--small", type=int, default=18)
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "gateway", "flip_font.h"))
    a = ap.parse_args()

    parts = ["// flip_font.h — GENERATED by tools/fonts/make_flip_font.py, do not edit.",
             f"// Font: {os.path.basename(a.font)}, weight {a.weight}. 8-bit alpha, cropped per glyph.",
             "#pragma once", "#include <stdint.h>",
             "struct FlipGlyph { uint32_t ofs; uint8_t w, h; int8_t x, y; uint8_t adv; };  // x,y = offset from the cell's top-left", ""]
    for name, chars, target in (("BIG", "0123456789-", a.big), ("SMALL", "0123456789:-", a.small)):
        font, size = size_for_height(a.font, a.weight, target)
        cap_h, glyphs, data = render(font, chars)
        parts.append(emit(name, chars, cap_h, glyphs, data))
        print(f"{name}: font size {size}, cap height {cap_h}, {len(data)} bytes")
    with open(a.out, "w") as f:
        f.write("\n".join(parts))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
