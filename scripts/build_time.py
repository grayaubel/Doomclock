# PlatformIO pre-build script: writes build_time.h with the current UTC time on EVERY build,
# so the gateway can show the correct time right after an upload, before NTP / with a reset RTC.
# (__DATE__/__TIME__ would be stale: PlatformIO only recompiles files that changed.)
# The header lives in the build directory (not in src/), so it never shows up in git.
import os, time
Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(gen_dir, exist_ok=True)
with open(os.path.join(gen_dir, "build_time.h"), "w") as f:
    f.write("// generated by scripts/build_time.py on every build\n#pragma once\n")
    f.write("#define BUILD_UNIX %dUL   // UTC seconds when this firmware was built\n" % int(time.time()))
env.Append(CPPPATH=[gen_dir])
